"""Predict forest/stone/mine counts on a randomly-generated map.

Closes Open Question P3 from project_extraction_model_plan.md by running the
same density math the game uses (dogenerate.inc) combined with empirically
calibrated per-pattern-type placement rates.

**Empirical validation (2026-04-29):** `PER_TYPE_PLACEMENT_TINY_HIGHLANDS_LAND`
calibrated against 10 sample replays in the homogeneous bucket
Tiny + Land + Highlands + 4pl_mask_nowater. Bucket ratios actual/predicted
all fall in 0.96-1.04 for forests_pine_*, stones, mng/mni/mnc.
Validation pipeline:
  parser/parse_replay_aggregates.py → derived/replay_ground_truth.json
  compute/validate_map_predictions.py  → internals/data/map_predictions_validation.md
Full guide: recon/map_generation_pipeline.md §14.

⚠ Calibration is *setting-specific*. On Huge maps / non-Highlands relief /
non-Land terrain, placement rates likely differ — for those, model falls back
to global `placement_success` parameter (default 0.65). Don't trust outputs
blindly outside the calibrated bucket without fresh replays.

Output: prints estimated counts and total wood pool. Also writes
docs/reports/map/map_resources.md.

Source code references:
- common.inc/dogenerate.inc:1688-1908 — density application and pattern calls
- lib/misc.script:3681-3737 — _misc_SetupPatternsByType (count = floor(W*H*freq))
- lib/misc.script:3876-3941 — _misc_GetFreePatternMaskCountModifier and ...Modifier
- data/game/var/generator.cfg — pattern-type → .pattern files registry

Trees per cluster come from `derived/pattern_type_stats.json`
(mask cell counts per pattern type, generated by parser/parse_pattern_inventory.py).
For each `forests_X_<size>` call we pick the median across all .pattern files
of that type. Different pattern types vary 10-30× — `forests_pine_big` median
~148 mask cells vs `forests_pinefir_big` ~920 vs `forests_mixed_big` ~1631.

⚠ Pattern format interpretation (settled 2026-04-29):

  mask=1 cells are PLACEMENT SLOTS for env-objects spawned by the C++ engine
  function `StandPatternWithAngle` (called from misc.script:3390).
  We CANNOT read that engine code, so we don't know precisely which slots
  become trees vs ground decoration.

  Empirically (per user observation): visible chopable trees ≈ 30% of mask
  cells. Cross-check: forests_pine_big has 148 mask median; user says big
  pine forest = ~50 trees → 50/148 ≈ 0.34. forests_pine_small mask 44 →
  user's ~10 trees → 10/44 ≈ 0.23. Average ~0.30.

  TREE_CHOPABLE_RATIO = 0.30 is the calibration used throughout. Different
  pattern types may have different real ratios — if you see in-game numbers
  that differ from the predictions in this report, refine per-type.

  Counter-examples to "1 cell = 1 object":
    - mines (mng/mni/mnc): mask = 32 cells exactly, but 1 mine deposit per
      pattern. The whole 32-cell mask is the deposit's collision footprint.
    - brushes (brush_plt_1x1): 8 mask cells = 8 visible bushes ✓ (1:1)
  So the ratio depends on pattern semantics, which is encoded in C++.

  For wood economy this is mostly academic — wood pool is INFINITE via
  stumps (see onaclanimationreachedwork.inc), and concurrent chop slots
  (maxattackers_wood=2 per tree) vastly exceed any reasonable farm cap.

CRITICAL — wood pool is INFINITE: when a tree's HP hits 0 the engine swaps
its mesh to a stump but `brised=True` is preserved, so peasants keep
chopping it indefinitely (1 hit = 1 hp = 1 wood, regardless of stump vs
whole tree). See onaclanimationreachedwork.inc:30-39 + ontagstates.inc:50-78.
"""
