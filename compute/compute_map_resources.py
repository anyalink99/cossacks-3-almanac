# C++ code (StandPatternWithAngle in misc.script:3390) decides which
# variant_id maps to which env-object class — we can't read that.
# For mines (mng/mni/mnc): mask = collision footprint, NOT individual objects
# (all 18 mine patterns have exactly 32 mask cells = ONE deposit).
TREE_CHOPABLE_RATIO = 0.30


def _trees_per_call(type_name: str, raw: bool = False) -> int:
    """Object count median for a given pattern type.

    By default returns the *visible chopable tree* estimate
    (median × TREE_CHOPABLE_RATIO). Pass raw=True for the literal mask
    cell count.
    """
    s = _TYPE_STATS.get(type_name)
    if not s:
        return 0
    if raw:
        return s["median"]
    # Mines: mask is footprint, not objects — return 1 deposit per pattern
    if type_name.startswith(("mng", "mni", "mnc", "desert_mng", "desert_mni", "desert_mnc")):
        return 1
    return round(s["median"] * TREE_CHOPABLE_RATIO)

